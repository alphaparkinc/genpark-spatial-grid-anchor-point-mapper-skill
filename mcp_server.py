import sys
import json
from client import SpatialGridMapper

mapper = SpatialGridMapper()

def handle_request(req):
    method = req.get("method")
    req_id = req.get("id")
    
    if method == "initialize":
        return {
            "jsonrpc": "2.0",
            "id": req_id,
            "result": {
                "protocolVersion": "2024-11-05",
                "capabilities": {"tools": {}},
                "serverInfo": {"name": "genpark-spatial-grid-anchor-point-mapper-skill", "version": "1.0.0"}
            }
        }
    elif method == "tools/list":
        return {
            "jsonrpc": "2.0",
            "id": req_id,
            "result": {
                "tools": [
                    {
                        "name": "map_box_to_grid",
                        "description": "Calculates center click coordinates and alphanumeric grid cell from a bounding box",
                        "inputSchema": {
                            "type": "object",
                            "properties": {
                                "box": {"type": "array", "items": {"type": "number"}},
                                "coord_format": {"type": "string", "enum": ["pixel", "normalized_0_1"], "default": "pixel"}
                            },
                            "required": ["box"]
                        }
                    }
                ]
            }
        }
    elif method == "tools/call":
        params = req.get("params", {})
        name = params.get("name")
        args = params.get("arguments", {})
        
        if name == "map_box_to_grid":
            res = mapper.map_box_to_anchor(args.get("box", []), args.get("coord_format", "pixel"))
            return {"jsonrpc": "2.0", "id": req_id, "result": {"content": [{"type": "text", "text": json.dumps(res, indent=2)}]}}
            
    return {"jsonrpc": "2.0", "id": req_id, "error": {"code": -32601, "message": "Method not found"}}

def run():
    for line in sys.stdin:
        if not line.strip():
            continue
        try:
            req = json.loads(line)
            res = handle_request(req)
            sys.stdout.write(json.dumps(res) + "\n")
            sys.stdout.flush()
        except Exception as e:
            sys.stdout.write(json.dumps({"jsonrpc": "2.0", "error": {"code": -32000, "message": str(e)}}) + "\n")
            sys.stdout.flush()

if __name__ == "__main__":
    run()
